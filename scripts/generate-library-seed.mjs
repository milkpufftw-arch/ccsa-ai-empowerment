import { readFileSync, writeFileSync } from "node:fs";
import { categories, resourceCategories, resources, showcases } from "../src/data/content.ts";

const groups = {
  showcases: categories,
  resources: [...resourceCategories.slice(1), "AI 基礎入門", "社會工作實務應用",
    "行政與工作效率", "GPT、Skill 與外掛資源", "AI 程式開發與自動化", "其他學習資源"],
};
const categoryIds = new Map();
const categoryRows = Object.entries(groups).flatMap(([module, names]) =>
  names.map((name, index) => {
    const id = `category_${module}_${index + 1}`;
    categoryIds.set(`${module}:${name}`, id);
    return { id, module, name, sortOrder: String(index + 1) };
  }),
);
const fixture = {
  LibraryCategories: categoryRows,
  Showcases: showcases.map(({ category, tools, steps, attachments, status, isDemo, ...item }, index) => ({
    ...item,
    categoryId: categoryIds.get(`showcases:${category}`),
    tools: tools.join("\n"),
    steps: steps.join("\n"),
    attachments: attachments.map((a) => `${a.label}｜${a.url}`).join("\n"),
    sortOrder: String(index + 1),
    sample: isDemo ? "sample" : "",
  })),
  LearningResources: resources.map(({ category, steps, ...item }, index) => ({
    ...item,
    summary: item.body,
    categoryId: categoryIds.get(`resources:${category}`),
    steps: steps.join("\n"),
    sortOrder: String(index + 1),
    type: ["操作指引", "提示詞", "課程", "操作指引", "操作指引"][index],
    sample: "sample",
  })),
};
const path = new URL("../apps-script/LibrarySeed.gs", import.meta.url);
const output = "// Generated by node scripts/generate-library-seed.mjs from the existing site content.\n" +
  "const LIBRARY_SEED_ = " + JSON.stringify(fixture, null, 2) + ";\n";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("Library seed is out of date.");
} else writeFileSync(path, output);
